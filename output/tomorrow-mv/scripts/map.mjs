// map.mjs: rasterise Natural Earth's 1:110m land polygons (public domain) into the dot grid the world and planet
// scenes draw → src/art/land.ts. Run again only to change the grid; the output is kept in the project.
//   node scripts/map.mjs [--step=4.5]
import {writeFileSync} from 'node:fs';
const SRC = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const step = +(process.argv.find((a) => a.startsWith('--step='))?.split('=')[1] ?? 4.5);
const LAT0 = 81, LAT1 = -57; // rows from 81°N down to 57°S (Antarctica left out)
const geo = await (await fetch(SRC)).json();
const rings = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const p of polys) rings.push(p[0]); // outer rings only; 1:110m land has no lakes worth a dot
}
const inside = (x, y, ring) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const cols = Math.round(360 / step), rows = Math.round((LAT0 - LAT1) / step) + 1;
const out = [];
for (let r = 0; r < rows; r++) {
  const lat = LAT0 - r * step;
  let s = '';
  for (let c = 0; c < cols; c++) {
    const lon = -180 + (c + 0.5) * step;
    // a dot is land if its centre, or most of a 3×3 neighbourhood, is land: keeps thin coasts and islands
    let n = 0;
    for (const dy of [-0.3, 0, 0.3]) for (const dx of [-0.3, 0, 0.3]) if (rings.some((ring) => inside(lon + dx * step, lat + dy * step, ring))) n++;
    s += n >= 4 ? '#' : '.';
  }
  out.push(s);
}
const body = `// land.ts: generated by scripts/map.mjs from Natural Earth 1:110m land (public domain). Do not edit by hand.
// One row per ${step}° of latitude from ${LAT0}°N; one column per ${step}° of longitude from 180°W; '#' = land.
export const LAND_STEP = ${step}, LAND_LAT0 = ${LAT0};
export const LAND = [
${out.map((s) => `  '${s}',`).join('\n')}
];
`;
writeFileSync(new URL('../src/art/land.ts', import.meta.url), body);
console.log(out.join('\n'));
