#!/usr/bin/env python3
"""analyze_master.py — per-frame audio features of the FINAL soundtrack (film time), for the picture to react to, and the
onsets the timeline snaps its cues to. numpy + ffmpeg.

    python3 tools/analyze_master.py      (reads out/audio/master.wav + assets/edit-plan.json) → src/music.js

Per video frame (30 fps): a 32-band log-spaced spectrum 40 Hz–14 kHz (2048-sample Hann window centred on the frame,
each band normalised by its 99th percentile over the film, 0–255), sub (25–70 Hz) and overall RMS envelopes (0–1), and a
'kick' value (positive low-band flux). Onsets: four-band spectral-flux peaks on the master (film time).
"""
import base64, json, os, subprocess
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
plan = json.load(open(os.path.join(ROOT, 'assets', 'edit-plan.json')))
SR, FPS = 48000, 30
raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', os.path.join(ROOT, plan['master']), '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'], capture_output=True, check=True).stdout
x = np.frombuffer(raw, dtype=np.float32).astype(np.float64)
NF = int(round(plan['end_s'] * FPS))
N = 2048
pad = np.pad(x, (N, N))
f = np.fft.rfftfreq(N, 1 / SR)
edges = np.geomspace(40, 14000, 33)
spec = np.zeros((NF, 32)); sub = np.zeros(NF); rms = np.zeros(NF)
win = np.hanning(N)
# bins per band; the lowest bands are narrower than one FFT bin (23.4 Hz) → use the nearest bin
BIN = []
for b in range(32):
    m = np.where((f >= edges[b]) & (f < edges[b + 1]))[0]
    BIN.append(m if len(m) else np.array([int(np.argmin(np.abs(f - np.sqrt(edges[b] * edges[b + 1]))))]))
for i in range(NF):
    c = int(i / FPS * SR) + N
    seg = pad[c - N // 2:c + N // 2]
    P = np.abs(np.fft.rfft(seg * win)) ** 2
    for b in range(32):
        spec[i, b] = 10 * np.log10(P[BIN[b]].mean() + 1e-12)
    sub[i] = 10 * np.log10(P[(f >= 25) & (f < 70)].sum() + 1e-12)
    rms[i] = 20 * np.log10(np.sqrt((seg ** 2).mean()) + 1e-12)
def norm(v, lo_pct=5, hi_pct=99):
    lo, hi = np.percentile(v, lo_pct), np.percentile(v, hi_pct)
    return np.clip((v - lo) / (hi - lo + 1e-9), 0, 1)
specN = np.stack([norm(spec[:, b], 10, 99) for b in range(32)], 1)
subN, rmsN = norm(sub, 5, 99), norm(rms, 5, 99)
# onsets on the master (STFT 1024/256)
H = 256; fr = np.lib.stride_tricks.sliding_window_view(np.pad(x, (512, 1024)), 1024)[::H][: len(x) // H]
L = np.log1p(1000 * np.abs(np.fft.rfft(fr * np.hanning(1024), axis=1))); ff = np.fft.rfftfreq(1024, 1 / SR); afps = SR / H
lv = 20 * np.log10(np.sqrt((fr ** 2).mean(1)) + 1e-12)
def flux(lo, hi):
    sel = (ff >= lo) & (ff < hi); d = np.maximum(np.diff(L[:, sel], axis=0, prepend=L[:1, sel]), 0).sum(1)
    return d / (np.percentile(d[lv > -40], 99) + 1e-9)
low = flux(30, 150); full = low + flux(150, 2000) + flux(2000, 6000) + flux(6000, 16000)
ons = []
w, g = int(0.5 * afps), int(0.06 * afps)
for i in range(1, len(full) - 1):
    loc = full[max(0, i - w):i + w]; med = np.median(loc)
    if lv[i] > -45 and full[i] >= med + 0.35 * (loc.max() - med) and full[i] == full[max(0, i - g):i + g + 1].max():
        ons.append([round(i / afps, 4), round(float(full[i]), 3)])
kick = np.zeros(NF)
for i in range(NF):
    a = int(i / FPS * afps); kick[i] = low[max(0, a - 2):a + 3].max() if a < len(low) else 0
kickN = np.clip(kick / 1.0, 0, 1)
pack = lambda arr: base64.b64encode((np.clip(arr, 0, 1) * 255).round().astype(np.uint8).tobytes()).decode()
music = {'fps': FPS, 'frames': NF, 'bands': 32, 'spec': pack(specN.reshape(-1)), 'sub': pack(subN), 'rms': pack(rmsN), 'kick': pack(kickN),
         'onsets': ons, 'events': plan['events_film'], 'bars': plan['bars_film'], 'end': plan['end_s']}
with open(os.path.join(ROOT, 'src', 'music.js'), 'w') as fh:
    fh.write('// music.js — GENERATED by tools/analyze_master.py from out/audio/master.wav (film time); do not edit by hand.\n')
    fh.write('export const MUSIC = ' + json.dumps(music, separators=(',', ':')) + ';\n')
print(f'{NF} frames, {len(ons)} onsets on the master; events {plan["events_film"]}')
