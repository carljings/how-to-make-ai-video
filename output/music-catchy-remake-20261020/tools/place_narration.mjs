#!/usr/bin/env node
// place_narration.mjs — put each narration line at the author's film time using its REAL duration and word boundaries
// (Codex's edge-tts batches), check that lines never overlap, never enter the music-only windows and fit before the end,
// and write src/narration.js. Lines whose current text has no real file yet get an ESTIMATE (≈ 0.24 s per character + 0.25 s; batch-1 lines ran 0.21–0.27 s per character)
// and the file is marked ESTIMATE — the film must not be frozen in that state.
//   node tools/place_narration.mjs [--dir <narration dir>]   (default: ../../.omx/artifacts/music-catchy-remake-20261020/narration)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const argv = process.argv.slice(2), opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : d; };
const DIR = path.resolve(ROOT, opt('dir', '../../.omx/artifacts/music-catchy-remake-20261020/narration'));
const REQ = JSON.parse(fs.readFileSync(path.join(ROOT, 'narration-request.json'), 'utf8'));

// author's placement (film s, start of the trimmed file, which has a 100 ms lead pad). Decided from the real durations.
const AT = { L01: 0.20, L02: 5.26, L03: 8.62, L04: 11.66, L05: 15.76, L06: 22.30, L07: 25.12, L08: 28.62, L09: 30.15, L10: 36.10, L11: 39.48 };
// music-only windows (must match src/timeline.js MUSIC_ONLY; checked again by tools/textcheck.mjs)
const MUSIC_ONLY = [[3.0667, 5.0167], [17.9627, 22.0907], [32.848, 35.8613]];
const END_MAX = 41.95;

const lines = [], problems = [];
let allReal = true;
for (const L of REQ.lines) {
  const meta = path.join(DIR, `${L.id}.json`);
  let real = null;
  if (fs.existsSync(meta)) {
    const m = JSON.parse(fs.readFileSync(meta, 'utf8'));
    const wav = path.join(DIR, m.file);
    if (m.text === L.text && fs.existsSync(wav)) {
      const sha = crypto.createHash('sha256').update(fs.readFileSync(wav)).digest('hex');
      if (sha !== m.sha256) problems.push(`${L.id}: wav sha256 mismatch`);
      const b = JSON.parse(fs.readFileSync(path.join(DIR, `${L.id}-boundaries.json`), 'utf8'));
      real = { dur: m.duration_s, file: m.file, sha256: sha, lufs: m.lufs, tp: m.true_peak_dbtp, words: b.filter((w) => w.type === 'WordBoundary').map((w) => ({ t: w.offset_s, d: w.duration_s, w: w.text })) };
    }
  }
  if (!real) allReal = false;
  const dur = real ? real.dur : +(0.24 * [...L.text].length + 0.25).toFixed(3);
  const at = AT[L.id];
  lines.push({ id: L.id, text: L.text, at, dur: +dur.toFixed(4), real: !!real, file: real?.file ?? null, sha256: real?.sha256 ?? null, lufs: real?.lufs ?? null, tp: real?.tp ?? null,
    words: (real?.words ?? []).map((w) => ({ t: +(at + w.t).toFixed(4), d: +w.d.toFixed(4), w: w.w })) });
}
lines.sort((a, b) => a.at - b.at);
for (let i = 0; i < lines.length; i++) {
  const L = lines[i], a = L.at + 0.1, b = L.at + L.dur - 0.1;   // speech inside the 100 ms pads
  if (i > 0 && L.at < lines[i - 1].at + lines[i - 1].dur + 0.05) problems.push(`${L.id} overlaps ${lines[i - 1].id}`);
  for (const [m0, m1] of MUSIC_ONLY) if (a < m1 && b > m0) problems.push(`${L.id} speech [${a.toFixed(2)}, ${b.toFixed(2)}] enters music-only window [${m0}, ${m1}] by ${Math.min(b, m1) - Math.max(a, m0) > 0 ? (Math.min(b, m1) - Math.max(a, m0)).toFixed(3) : 0} s`);
  if (L.at + L.dur > END_MAX) problems.push(`${L.id} ends after ${END_MAX}`);
}
const status = allReal ? 'REAL' : 'ESTIMATE';
const js = `// narration.js — GENERATED by tools/place_narration.mjs (do not hand-edit). Film times (s) of each line (start of the
// trimmed TTS file, 100 ms lead pad) and its word boundaries (edge-tts WordBoundary, shifted to film time).
// STATUS ${status}: ${allReal ? 'every line is a real TTS file (sha256 below)' : 'some lines are ESTIMATES (no real file for the current text yet) — do not freeze'}.
export const NARR_STATUS = '${status}';
export const NARR = ${JSON.stringify(lines.map(({ lufs, tp, ...l }) => l), null, 1)};
`;
fs.writeFileSync(path.join(ROOT, 'src/narration.js'), js);
for (const L of lines) console.log(`${L.id} ${L.real ? 'REAL    ' : 'ESTIMATE'} at ${L.at.toFixed(2)} dur ${L.dur.toFixed(3)} → ${(L.at + L.dur).toFixed(2)}  ${L.text}`);
if (problems.length) { console.log('PROBLEMS:\n  ' + problems.join('\n  ')); process.exit(2); }
console.log(`status ${status}; no overlaps; music-only windows clear`);
