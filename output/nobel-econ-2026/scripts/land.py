"""Rasterize Natural Earth 1:110m land onto dots for the globe and write src/art/land.ts.

Usage: python3 scripts/land.py ne_110m_land.geojson src/art/land.ts
Data (public domain): https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
"""
import json, math, sys
src, out = sys.argv[1], sys.argv[2]
polys = []
for f in json.load(open(src))['features']:
    g = f['geometry']
    rings = [g['coordinates']] if g['type'] == 'Polygon' else g['coordinates']
    for poly in rings:
        polys.append(poly)  # [outer, holes...]
def inside(ring, x, y):
    c = False
    for i in range(len(ring)):
        x1, y1 = ring[i - 1]; x2, y2 = ring[i]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c
def land(lon, lat):
    for poly in polys:
        if inside(poly[0], lon, lat) and not any(inside(h, lon, lat) for h in poly[1:]):
            return True
    return False
STEP = 2.6  # degrees between dot rows
pts = []
lat = -58.0  # skip Antarctica
while lat <= 80:
    n = max(1, round(360 * math.cos(math.radians(lat)) / STEP))  # fewer dots near the poles: even spacing on the sphere
    for i in range(n):
        lon = -180 + (i + 0.5) * 360 / n
        if land(lon, lat):
            pts.append((round(lon, 1), round(lat, 1)))
    lat += STEP
flat = ','.join(f'{a},{b}' for a, b in pts)
open(out, 'w').write('// land.ts: dots on land for the globe, from Natural Earth 1:110m land (public domain), generated by scripts/land.py.\n'
                     f'// {len(pts)} dots, {STEP}° apart, as a flat [lon, lat, lon, lat, …] list.\n'
                     f'export const LAND = [{flat}];\n')
print(len(pts), 'land dots')
