"""export_v2_overlay.py: per-frame vector overlay for Remotion (pure Python, same state and camera as the plates).

    python3 blender/tools/export_v2_overlay.py          # -> src/v2/data/overlay.json

Each frame: s section, ev source-clock time, and (frozen sections only) p gas particles [x0,y0,x1,y1,w,a],
b force lines [port,x0,y0,x1,y1,level], l line of action, c CoM [x,y,level], arm (CoM to the line of action),
a torque arc {pts, lv, draw}, fl flow paths {paths, lv, phase}, vl vessel label anchor [x,y,level]. 1080x1920 px.
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import v2_film  # noqa: E402

OUT = os.path.join(v2_film.ROOT, 'src', 'v2', 'data', 'overlay.json')


def main():
    frames = []
    for k in range(v2_film.N_FRAMES):
        fr = v2_film.state(k / v2_film.FPS)
        frames.append(v2_film.overlay(fr))
    sha = hashlib.sha256(open(v2_film.CUES_PATH, 'rb').read()).hexdigest()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        json.dump({'about': 'Generated by blender/tools/export_v2_overlay.py from v2_film.overlay(); do not edit.',
                   'cues_sha256': sha, 'fps': v2_film.FPS, 'width': v2_film.W_PX, 'height': v2_film.H_PX,
                   'frames': frames}, fh, ensure_ascii=False, separators=(',', ':'))
    n = sum(1 for f in frames if len(f) > 3)
    print('wrote %s: %d frames (%d with graphics), %.0f kB' % (os.path.relpath(OUT, v2_film.ROOT), len(frames), n,
                                                             os.path.getsize(OUT) / 1024))


if __name__ == '__main__':
    main()
