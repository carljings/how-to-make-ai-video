"""export_v3_overlay.py: per-frame vector overlay + plate manifest for Remotion (pure Python; same state and cameras
as the Blender plates, via v3_film).

    python3 blender/tools/export_v3_overlay.py     # -> src/v3/data/overlay.json, src/v3/data/plates.json

overlay.json frames (1080x1920 output px), keys present only when drawn:
  air [[x0,y0,x1,y1,w,a]] warm air streaks; ticks [[x0,y0,x1,y1,a]] pressure impacts (tail -> skin);
  gap {pts, lv, label} low-pressure lens; fan [[x,y,a]] schematic intakes; grav / press arrows [x0,y0,x1,y1,lv,kind];
  flash [x0,y0,x1,y1,lv]; contact [[x,y,r,a]]; trac [arrows]; lip [x0,y0,x1,y1,lv]; shards [[x,y,r,a]];
  scan {p, axis, prog}; vl [x,y,lv]; relay {pts, prog, lv}; jet [[x0,y0,x1,y1,w,a]]; react [arrows];
  ghosts [{press, grav, pulse, vcomp}]; cold [{jet, react, lv, live}]; crop [x0,y0,w,h] (poster px);
  k2: loa [x0,y0,x1,y1,lv], com [x,y,lv], arm [...], arc {pts, lv, draw}, v2f (v2 plate frame).
plates.json: one entry per film frame: r (v3 render frame f), s (still id + zoom z), w (wipe a/b + zoom),
  v2 (v2 plate frame f), 0 (black), p (poster: crop, ghosts [{id, op}], live {f}|{still}, cloud level).
"""
import hashlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import v3_film as F  # noqa: E402

OUT_DIR = os.path.join(F.ROOT, 'src', 'v3', 'data')


def main():
    t0 = time.perf_counter()
    frames, plates = [], []
    for k in range(F.N_FRAMES):
        fr = F.state(k / F.FPS)
        frames.append(F.overlay(fr))
        plates.append(F.plate_for(k))
    cues_sha = hashlib.sha256(open(F.CUES_PATH, 'rb').read()).hexdigest()
    timing_sha = hashlib.sha256(open(F.TIMING_PATH, 'rb').read()).hexdigest() if F.TIMING else None
    os.makedirs(OUT_DIR, exist_ok=True)
    head = {'cues_sha256': cues_sha, 'timing_sha256': timing_sha, 'fps': F.FPS, 'width': F.W_PX, 'height': F.H_PX,
            'poster': [F.POSTER_W, F.POSTER_H]}
    with open(os.path.join(OUT_DIR, 'overlay.json'), 'w', encoding='utf-8') as fh:
        json.dump(dict(about='Generated by blender/tools/export_v3_overlay.py from v3_film.overlay(); do not edit.',
                       frames=frames, **head), fh, ensure_ascii=False, separators=(',', ':'))
    with open(os.path.join(OUT_DIR, 'plates.json'), 'w', encoding='utf-8') as fh:
        json.dump(dict(about='Generated by blender/tools/export_v3_overlay.py from v3_film.plate_for(); do not edit.',
                       anchors={k: round(v, 3) for k, v in F.A.items()}, ghosts_ramp=[round(e, 3) for e in F.GHOSTS_RAMP],
                       ghosts_air=F.GHOSTS_AIR, layer_frames=F.LAYER_FRAMES, render_frames=F.render_frames(),
                       sheet={'in': F.SHEET_IN[0], 'lock': F.SHEET_IN[1], 'tyre': F.SEC['press_tyre']['start'],
                              'tyre_slide': F.TYRE_SLIDE, 'boundary': round(F.ENDING_OFF_T, 3)},
                       stills=sorted(F.STILLS), plates=plates, **head), fh, ensure_ascii=False, separators=(',', ':'))
    n = sum(1 for f in frames if len(f) > 3)
    size = os.path.getsize(os.path.join(OUT_DIR, 'overlay.json')) / 1024
    print('wrote src/v3/data/overlay.json (%d frames, %d with graphics, %.0f kB) and plates.json in %.1fs; timing %s' % (
        len(frames), n, size, time.perf_counter() - t0, 'measured' if F.TIMING else 'NOMINAL'))


if __name__ == '__main__':
    main()
